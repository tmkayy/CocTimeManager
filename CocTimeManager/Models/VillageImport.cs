using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using Avalonia.Platform;

namespace CocTimeManager.Models;

/// <summary>One running upgrade found in a village export.</summary>
/// <param name="Key">Identifies the item across exports: section, game id and current level.</param>
public sealed record ImportedTimer(string Key, string Name, DateTime FinishAt);

/// <param name="BuilderBoostLeft">Builder Potion time left at export (zero if none was active).</param>
/// <param name="BoostedCount">How many timers the active Builder Potion was applied to.</param>
/// <param name="LabBoostLeft">Research Potion time left at export (zero if none was active).</param>
/// <param name="LabBoostedCount">How many timers the active Research Potion was applied to.</param>
/// <param name="HelperCount">How many timers finish sooner thanks to a helper session, now or repeating later.</param>
public sealed record VillageExport(string Tag, DateTime ExportedAt, List<ImportedTimer> Timers,
                                   TimeSpan BuilderBoostLeft, int BoostedCount,
                                   TimeSpan LabBoostLeft, int LabBoostedCount, int HelperCount);

/// <summary>What an import changes: <see cref="Removed"/> are all previously imported entries,
/// <see cref="Added"/> their replacements; <see cref="Kept"/> of them continue an earlier entry.</summary>
public sealed record ImportMerge(List<TrackedUpgrade> Removed, List<TrackedUpgrade> Added, int Kept);

/// <summary>
/// Reads the JSON from the game's Settings → "Export village data" (copied to the clipboard).
/// Every running upgrade has <c>"timer"</c> = seconds left at the export's <c>"timestamp"</c> (Unix, UTC).
/// Sections ending in "2" (buildings2, units2, ...) are the Builder Base.
/// <para>
/// <c>timer</c> is work left at normal speed: active boosts are NOT taken into account. Time left on potions
/// is in <c>boosts.builder_boost</c> and <c>boosts.lab_boost</c> (seconds); an item a helper is working on has
/// <c>helper_timer</c> (seconds), and the helper's level is in the <c>helpers</c> section.
/// </para>
/// <para>
/// Speeds add up. Measured across exports while both potions ran: other builder timers dropped 10× and lab
/// timers 24× (including the <c>extra</c> slot), the one with the level 8 Apprentice 18× and the one with the
/// level 12 Lab Assistant 36× until <c>helper_timer</c> ran out; pets and the Builder Base dropped 1×.
/// </para>
/// <para>
/// <c>helper_recurrent</c> is the player's choice to have the helper reapply itself to that item whenever
/// <c>helper_cooldown</c> ends. The cooldown counts from the start of a session, so sessions repeat every 23 h.
/// </para>
/// </summary>
public static class VillageImport
{
    private static readonly Dictionary<string, string> Kinds = new()
    {
        ["buildings"] = "Building", ["traps"] = "Trap", ["units"] = "Troop", ["siege_machines"] = "Siege Machine",
        ["heroes"] = "Hero", ["spells"] = "Spell", ["pets"] = "Pet", ["equipment"] = "Equipment",
        ["guardians"] = "Guardian", ["decos"] = "Decoration",
    };

    /// <summary>Home-village sections worked on by builders, so sped up by a Builder Potion and the Apprentice.
    /// Not the lab, pets, equipment or the Builder Base.</summary>
    private static readonly HashSet<string> BuilderSections = ["buildings", "traps", "heroes", "guardians"];

    /// <summary>Home-village lab sections, so sped up by a Research Potion and the Lab Assistant.</summary>
    private static readonly HashSet<string> LabSections = ["units", "spells", "siege_machines"];

    private const long BuilderApprenticeId = 93000000, LabAssistantId = 93000001;

    private static readonly TimeSpan HelperSession = TimeSpan.FromHours(1), HelperCooldown = TimeSpan.FromHours(23);

    private static Dictionary<string, string>? _names;

    /// <summary>Game id -> name, generated by scripts/update-game-names.py.</summary>
    private static Dictionary<string, string> Names => _names ??= LoadNames();

    private static Dictionary<string, string> LoadNames()
    {
        try
        {
            using var s = AssetLoader.Open(new Uri("avares://CocTimeManager/Data/game_names.json"));
            return JsonSerializer.Deserialize<Dictionary<string, string>>(s) ?? [];
        }
        catch (Exception)
        {
            return [];
        }
    }

    /// <summary>Parses an export. Throws <see cref="FormatException"/> if it isn't one.</summary>
    public static VillageExport Parse(string json)
    {
        JsonDocument doc;
        try
        {
            doc = JsonDocument.Parse(json.Trim());
        }
        catch (JsonException)
        {
            throw new FormatException("The clipboard doesn't contain village data JSON.");
        }

        using (doc)
        {
            var root = doc.RootElement;
            if (root.ValueKind != JsonValueKind.Object ||
                !root.TryGetProperty("timestamp", out var tsEl) || !tsEl.TryGetInt64(out var ts))
                throw new FormatException("That JSON isn't a village export (no \"timestamp\").");

            var exportedAt = DateTimeOffset.FromUnixTimeSeconds(ts).UtcDateTime;
            var tag = root.TryGetProperty("tag", out var tagEl) && tagEl.ValueKind == JsonValueKind.String
                ? tagEl.GetString() ?? "" : "";

            var builderBoost = BoostLeft(root, "builder_boost");
            var labBoost = BoostLeft(root, "lab_boost");
            var apprentice = FindHelper(root, BuilderApprenticeId);
            var assistant = FindHelper(root, LabAssistantId);
            int boosted = 0, labBoosted = 0, helped = 0;

            var timers = new List<ImportedTimer>();
            foreach (var section in root.EnumerateObject().Where(p => p.Value.ValueKind == JsonValueKind.Array))
            {
                var builderBase = section.Name.EndsWith('2');
                var baseSection = builderBase ? section.Name[..^1] : section.Name;

                foreach (var item in section.Value.EnumerateArray())
                {
                    if (item.ValueKind != JsonValueKind.Object ||
                        !item.TryGetProperty("timer", out var timerEl) || !timerEl.TryGetInt64(out var secondsLeft) ||
                        !item.TryGetProperty("data", out var idEl) || !idEl.TryGetInt64(out var id))
                        continue;

                    var lvl = item.TryGetProperty("lvl", out var lvlEl) && lvlEl.TryGetInt32(out var l) ? l : 0;
                    var name = Names.TryGetValue(id.ToString(), out var n)
                        ? n
                        : $"{Kinds.GetValueOrDefault(baseSection, "Item")} #{id}"; // newer than our name table
                    var label = $"{name} → {lvl + 1}{(builderBase ? " (Builder Base)" : "")}";

                    var isBuilder = BuilderSections.Contains(section.Name);
                    var isLab = LabSections.Contains(section.Name);
                    var work = TimeSpan.FromSeconds(secondsLeft);
                    var (potionLeft, potionExtra) = isBuilder ? (builderBoost, UpgradeCalculator.PotionSpeedMultiplier - 1)
                        : isLab ? (labBoost, UpgradeCalculator.ResearchPotionSpeedMultiplier - 1)
                        : (TimeSpan.Zero, 0);
                    List<(TimeSpan, TimeSpan, int)> potion = [(TimeSpan.Zero, potionLeft, potionExtra)];
                    var boosts = potion.Concat(HelperSessions(item, work, isBuilder ? apprentice : isLab ? assistant : default)).ToList();

                    if (potionLeft > TimeSpan.Zero)
                    {
                        if (isBuilder) boosted++;
                        else labBoosted++;
                    }

                    var timeLeft = UpgradeCalculator.TimeToFinish(work, boosts);
                    if (timeLeft < UpgradeCalculator.TimeToFinish(work, potion)) helped++;

                    var finish = exportedAt + timeLeft;
                    timers.Add(new ImportedTimer($"{section.Name}:{id}:{lvl}", label, finish));
                }
            }

            return new VillageExport(tag, exportedAt, timers.OrderBy(t => t.FinishAt).ToList(),
                                     builderBoost, boosted, labBoost, labBoosted, helped);
        }
    }

    private static TimeSpan BoostLeft(JsonElement root, string name) =>
        root.TryGetProperty("boosts", out var boosts) && boosts.ValueKind == JsonValueKind.Object &&
        boosts.TryGetProperty(name, out var el) && el.TryGetInt64(out var seconds) && seconds > 0
            ? TimeSpan.FromSeconds(seconds) : TimeSpan.Zero;

    /// <summary>The helper's session running on this item, plus future ones if it's set to reapply itself.
    /// Work never takes longer than its time at normal speed, so sessions after that can't matter.</summary>
    private static IEnumerable<(TimeSpan, TimeSpan, int)> HelperSessions(JsonElement item, TimeSpan work,
                                                                         (int Level, TimeSpan Cooldown) helper)
    {
        if (helper.Level <= 0) yield break;

        if (item.TryGetProperty("helper_timer", out var timerEl) && timerEl.TryGetInt64(out var left) && left > 0)
            yield return (TimeSpan.Zero, TimeSpan.FromSeconds(left), helper.Level);

        if (!item.TryGetProperty("helper_recurrent", out var recurrent) || recurrent.ValueKind != JsonValueKind.True ||
            helper.Cooldown <= TimeSpan.Zero)
            yield break;

        for (var start = helper.Cooldown; start < work; start += HelperCooldown)
            yield return (start, start + HelperSession, helper.Level);
    }

    private static (int Level, TimeSpan Cooldown) FindHelper(JsonElement root, long helperId)
    {
        if (!root.TryGetProperty("helpers", out var helpers) || helpers.ValueKind != JsonValueKind.Array) return default;
        foreach (var h in helpers.EnumerateArray())
            if (h.ValueKind == JsonValueKind.Object &&
                h.TryGetProperty("data", out var id) && id.TryGetInt64(out var i) && i == helperId &&
                h.TryGetProperty("lvl", out var lvl) && lvl.TryGetInt32(out var level))
                return (level, h.TryGetProperty("helper_cooldown", out var cd) && cd.TryGetInt64(out var seconds)
                    ? TimeSpan.FromSeconds(seconds) : TimeSpan.Zero);
        return default;
    }

    /// <summary>
    /// Replaces previously imported upgrades with the ones in <paramref name="export"/>; hand-added ones are left alone.
    /// An upgrade seen in an earlier import keeps its id, start time and notified state.
    /// Returns null if the export is older than the last one imported.
    /// </summary>
    public static ImportMerge? Merge(IEnumerable<TrackedUpgrade> tracked, VillageExport export, DateTime nowUtc)
    {
        var old = tracked.Where(t => t.ImportKey is not null).ToList();
        if (old.Count > 0 && export.ExportedAt < old.Max(t => t.ImportedAt)) return null;

        var matched = new HashSet<TrackedUpgrade>();
        var added = new List<TrackedUpgrade>();
        foreach (var timer in export.Timers)
        {
            // Same item and level; with duplicates (e.g. two Giant Bombs) the closest finish time wins.
            var prev = old
                .Where(o => !matched.Contains(o) && o.ImportKey == timer.Key)
                .OrderBy(o => Math.Abs((o.FinishAt - timer.FinishAt).Ticks))
                .FirstOrDefault();
            if (prev is not null) matched.Add(prev);

            var doneAlready = timer.FinishAt <= nowUtc;
            added.Add(new TrackedUpgrade
            {
                Id = prev?.Id ?? Guid.NewGuid(),
                Name = timer.Name,
                ImportKey = timer.Key,
                ImportedAt = export.ExportedAt,
                UpdatedAt = nowUtc,
                // The export only has the time left, so a new item's progress counts from the export.
                StartedAt = prev?.StartedAt ?? (doneAlready ? timer.FinishAt : export.ExportedAt),
                FinishAt = timer.FinishAt,
                // Finished before the import (old export): show as done, no notification.
                Notified = (prev?.Notified ?? false) || doneAlready,
            });
        }
        return new ImportMerge(old, added, matched.Count);
    }
}
